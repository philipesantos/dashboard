use tauri_build::{AppManifest, Attributes};

/// Expands the shared command list into `APP_COMMANDS`.
macro_rules! commands {
    ($($command:ident),* $(,)?) => {
        /// The app's own commands.
        const APP_COMMANDS: &[&str] = &[$(stringify!($command)),*];
    };
}
include!("src/commands.rs");

/// The shell probe's two commands, for the `shell-probe` build only.
const PROBE_COMMANDS: &[&str] = &[
    "shell_probe_report",
    "shell_probe_ungranted",
    "shell_probe_tree",
];

/// Where tauri-build writes one permission file per app command, `<command>.toml`. It never
/// deletes a file there, and it reads every file in `permissions/`, so a probe build would leave
/// its commands' permissions in every later build's ACL. `prune` removes the files of commands
/// this build does not have. It leaves the others alone: tauri-build rewrites a file only when its
/// text changes, and `tauri dev` rebuilds whenever a file there changes, so emptying the folder
/// made it rebuild forever.
const AUTOGENERATED: &str = "permissions/autogenerated";

/// The packages every build embeds, from `target/plugins/` (`cargo xtask plugins`).
const BUNDLED: &[&str] = &["showcase"];

/// The hostile widgets the shell probe also embeds; never in a build anyone runs
/// (specs/009-declarative-widget-ui/research.md, R14). They join as they are written.
const PROBE_BUNDLED: &[&str] = &[
    "ui-invalid",
    "ui-crash",
    "ui-badmanifest",
    "ui-header",
    "ui-overflow",
    "ui-strings",
    "ui-dialog",
];

/// The releases the probe's release source serves, as `github.com/dashboard-fixtures/<name>`:
/// only in the probe build (specs/010-plugin-installation/research.md, R16).
const PROBE_RELEASES: &[&str] = &["install-basic", "compile-heavy"];

/// Writes `$OUT_DIR/releases.rs`: the `PROBE_RELEASES` list of `src/widgets.rs`, empty unless this
/// is the probe build.
fn embed_releases(probe: bool) {
    let root = std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../..");
    let plugins = root.join("target").join("plugins");
    let mut out = String::from(
        "/// The releases the probe's source serves: none outside the probe build.\npub const PROBE_RELEASES: &[(&str, &[u8])] = &[\n",
    );
    for name in if probe { PROBE_RELEASES } else { &[] } {
        let path = plugins.join(format!("{name}.wasm"));
        let path = path.canonicalize().unwrap_or_else(|_| {
            panic!(
                "{} is missing: run `cargo xtask plugins` first",
                path.display()
            )
        });
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            path.display().to_string()
        ));
    }
    out.push_str("];\n");
    let target = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("releases.rs");
    std::fs::write(&target, out).unwrap_or_else(|error| panic!("{}: {error}", target.display()));
}

/// Writes `$OUT_DIR/bundled.rs`: the `BUNDLED` list of `src/widgets.rs`, each package included
/// from the file `cargo xtask plugins` built (research R1).
fn embed(probe: bool) {
    let root = std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../..");
    let plugins = root.join("target").join("plugins");
    let names = BUNDLED
        .iter()
        .chain(if probe { PROBE_BUNDLED } else { &[] });
    let mut out = String::from(
        "/// The packages this build embeds.\npub const BUNDLED: &[Bundled<'static>] = &[\n",
    );
    for name in names {
        let path = plugins.join(format!("{name}.wasm"));
        let path = path.canonicalize().unwrap_or_else(|_| {
            panic!(
                "{} is missing: run `cargo xtask plugins` first",
                path.display()
            )
        });
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    Bundled {{ file: {:?}, bytes: include_bytes!({:?}) }},\n",
            format!("{name}.wasm"),
            path.display().to_string()
        ));
    }
    out.push_str("];\n");
    let target = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("bundled.rs");
    std::fs::write(&target, out).unwrap_or_else(|error| panic!("{}: {error}", target.display()));
}

/// Removes from `AUTOGENERATED` every file that is not one of `commands`' permission files.
fn prune(commands: &[&str]) {
    let entries = match std::fs::read_dir(AUTOGENERATED) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return,
        Err(error) => panic!("cannot read {AUTOGENERATED}: {error}"),
    };
    for entry in entries {
        let path = entry
            .unwrap_or_else(|error| panic!("cannot read {AUTOGENERATED}: {error}"))
            .path();
        let kept = path
            .extension()
            .is_some_and(|extension| extension == "toml")
            && path
                .file_stem()
                .and_then(|stem| stem.to_str())
                .is_some_and(|stem| commands.contains(&stem));
        if !kept {
            std::fs::remove_file(&path)
                .unwrap_or_else(|error| panic!("cannot remove {}: {error}", path.display()));
        }
    }
}

fn main() {
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_SHELL_PROBE");
    println!("cargo:rerun-if-changed=build.rs");
    embed(std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some());
    embed_releases(std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some());
    println!("cargo:rerun-if-changed=src/commands.rs");
    let commands: &'static [&'static str] =
        if std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some() {
            Vec::leak([APP_COMMANDS, PROBE_COMMANDS].concat())
        } else {
            APP_COMMANDS
        };
    prune(commands);
    tauri_build::try_build(Attributes::new().app_manifest(AppManifest::new().commands(commands)))
        .expect("failed to run tauri-build");
}
