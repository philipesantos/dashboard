use tauri_build::{AppManifest, Attributes};

/// The app's own commands. None yet (spec 008: the window starts with no host command).
const APP_COMMANDS: &[&str] = &[];

/// The app's commands plus the shell probe's two, for the `shell-probe` build only.
const PROBE_COMMANDS: &[&str] = &["shell_probe_report", "shell_probe_ungranted"];

/// Where tauri-build writes one permission file per app command. It never deletes a file there,
/// and it reads every file in `permissions/`, so a probe build would leave its commands'
/// permissions in every later build's ACL. Emptying it first makes it match this build's list.
const AUTOGENERATED: &str = "permissions/autogenerated";

fn main() {
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_SHELL_PROBE");
    match std::fs::remove_dir_all(AUTOGENERATED) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => panic!("cannot empty {AUTOGENERATED}: {error}"),
    }
    let commands = if std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some() {
        PROBE_COMMANDS
    } else {
        APP_COMMANDS
    };
    tauri_build::try_build(Attributes::new().app_manifest(AppManifest::new().commands(commands)))
        .expect("failed to run tauri-build");
}
