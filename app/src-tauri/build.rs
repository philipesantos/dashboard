use tauri_build::{AppManifest, Attributes};

/// Expands the shared command list into `APP_COMMANDS`.
macro_rules! commands {
    ($($command:ident),* $(,)?) => {
        /// The app's own commands.
        const APP_COMMANDS: &[&str] = &[$(stringify!($command)),*];
    };
}
include!("src/commands.rs");

/// The shell probe's two commands, for the `shell-probe` build only.
const PROBE_COMMANDS: &[&str] = &["shell_probe_report", "shell_probe_ungranted"];

/// Where tauri-build writes one permission file per app command. It never deletes a file there,
/// and it reads every file in `permissions/`, so a probe build would leave its commands'
/// permissions in every later build's ACL. Emptying it first makes it match this build's list.
const AUTOGENERATED: &str = "permissions/autogenerated";

/// The packages every build embeds, from `target/plugins/` (`cargo xtask plugins`).
const BUNDLED: &[&str] = &["showcase"];

/// The hostile widgets the shell probe also embeds; never in a build anyone runs
/// (specs/009-declarative-widget-ui/research.md, R14). They join as they are written.
const PROBE_BUNDLED: &[&str] = &[
    "ui-invalid",
    "ui-crash",
    "ui-badmanifest",
    "ui-header",
    "ui-overflow",
    "ui-strings",
    "ui-dialog",
];

/// Writes `$OUT_DIR/bundled.rs`: the `BUNDLED` list of `src/widgets.rs`, each package included
/// from the file `cargo xtask plugins` built (research R1).
fn embed(probe: bool) {
    let root = std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../..");
    let plugins = root.join("target").join("plugins");
    let names = BUNDLED
        .iter()
        .chain(if probe { PROBE_BUNDLED } else { &[] });
    let mut out = String::from(
        "/// The packages this build embeds.\npub const BUNDLED: &[Bundled<'static>] = &[\n",
    );
    for name in names {
        let path = plugins.join(format!("{name}.wasm"));
        let path = path.canonicalize().unwrap_or_else(|_| {
            panic!(
                "{} is missing: run `cargo xtask plugins` first",
                path.display()
            )
        });
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    Bundled {{ file: {:?}, bytes: include_bytes!({:?}) }},\n",
            format!("{name}.wasm"),
            path.display().to_string()
        ));
    }
    out.push_str("];\n");
    let target = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("bundled.rs");
    std::fs::write(&target, out).unwrap_or_else(|error| panic!("{}: {error}", target.display()));
}

fn main() {
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_SHELL_PROBE");
    println!("cargo:rerun-if-changed=build.rs");
    embed(std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some());
    println!("cargo:rerun-if-changed=src/commands.rs");
    match std::fs::remove_dir_all(AUTOGENERATED) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => panic!("cannot empty {AUTOGENERATED}: {error}"),
    }
    let commands: &'static [&'static str] =
        if std::env::var_os("CARGO_FEATURE_SHELL_PROBE").is_some() {
            Vec::leak([APP_COMMANDS, PROBE_COMMANDS].concat())
        } else {
            APP_COMMANDS
        };
    tauri_build::try_build(Attributes::new().app_manifest(AppManifest::new().commands(commands)))
        .expect("failed to run tauri-build");
}
